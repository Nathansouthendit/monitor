#!/usr/bin/env bash
# cloudflare-lockdown.sh - run as root on the VPS once the site is working through Cloudflare.
#
#  1. Writes /etc/nginx/conf.d/cloudflare-realip.conf so nginx (and the app) see the real
#     visitor IP instead of Cloudflare's.
#  2. Changes ufw so ports 80/443 accept connections ONLY from Cloudflare. Nobody can skip
#     Cloudflare by connecting to the server's IP directly. SSH is not touched.
#
# Cloudflare occasionally adds ranges, so run it monthly from root's crontab:
#     0 4 1 * *  /opt/monitor-dashboard/deploy/cloudflare-lockdown.sh >/var/log/cloudflare-lockdown.log 2>&1
#
# Before running: in Cloudflare set SSL/TLS mode to "Full (strict)" and make sure the
# dashboard's DNS record is proxied (orange cloud).
set -euo pipefail

REALIP_CONF=/etc/nginx/conf.d/cloudflare-realip.conf
TMP=$(mktemp)
trap 'rm -f "$TMP" "$TMP.v4" "$TMP.v6"' EXIT

curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4 -o "$TMP.v4"
curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6 -o "$TMP.v6"

# Sanity check: refuse to continue with an empty or garbled list (would lock everyone out)
v4=$(grep -cE '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+/[0-9]+$' "$TMP.v4" || true)
v6=$(grep -cE '^[0-9a-f:]+/[0-9]+$' "$TMP.v6" || true)
if [ "$v4" -lt 10 ] || [ "$v6" -lt 5 ]; then
    echo "Cloudflare IP list looks wrong (v4=$v4 v6=$v6) - nothing changed." >&2
    exit 1
fi

# --- 1. nginx real IP -------------------------------------------------------
{
    echo "# Generated by cloudflare-lockdown.sh on $(date -Is) - do not edit by hand"
    cat "$TMP.v4" "$TMP.v6" | grep -v '^$' | sed 's/^/set_real_ip_from /; s/$/;/'
    echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"
install -m 644 "$TMP" "$REALIP_CONF"
nginx -t
systemctl reload nginx
echo "Wrote $REALIP_CONF"

# --- 2. ufw: web ports from Cloudflare only ---------------------------------
# Remove any existing open-to-the-world web rules, then any old Cloudflare rules.
ufw --force delete allow 'Nginx Full' >/dev/null 2>&1 || true
ufw --force delete allow 'Nginx HTTP' >/dev/null 2>&1 || true
ufw --force delete allow 'Nginx HTTPS' >/dev/null 2>&1 || true
ufw --force delete allow 80/tcp >/dev/null 2>&1 || true
ufw --force delete allow 443/tcp >/dev/null 2>&1 || true
while read -r num; do
    ufw --force delete "$num" >/dev/null
done < <(ufw status numbered | grep 'cloudflare' | grep -oE '^\[ *[0-9]+\]' | tr -d '[] ' | sort -rn)

while read -r cidr; do
    [ -n "$cidr" ] || continue
    ufw allow proto tcp from "$cidr" to any port 80,443 comment 'cloudflare' >/dev/null
done < <(cat "$TMP.v4" "$TMP.v6")

ufw reload >/dev/null
echo "ufw: ports 80/443 now accept Cloudflare only ($v4 IPv4 + $v6 IPv6 ranges)."
ufw status | grep -E 'OpenSSH|22' || echo "WARNING: no SSH rule seen in ufw - check before logging out!"
